import { $, browser, expect } from '@wdio/globals';
import { it } from 'mocha';
import { getTestPreferences } from '../e2e-browser/fixtures';

it('shares native host Settings and keeps guidance nonmodal in the actual webview', async () => {
  await browser.tauri.execute(({ core }) => core.invoke('patch_preferences', { patch: { guidance: { enabled: true, resetAcknowledgments: true } } }));
  await $('[aria-label="Open settings"]').click();
  const settings = $('//div[@role="dialog"][.//h2[text()="Settings"]]');
  await expect(settings).toHaveText(expect.stringContaining('desktop installation'));
  await browser.waitUntil(async () => Number((await settings.getCSSProperty('opacity')).value) === 1);
  await browser.saveScreenshot('native-settings-general.png');
  await settings.$('button=AI').click();
  await expect($('h2=AI connections')).toBeDisplayed();
  await settings.$('button=Portal').click();
  await expect($('h2=Portal access')).toBeDisplayed();
  await expect($('input[type="password"]')).toHaveValue('');
  await expect($('[aria-label="Portal credential storage"]')).toHaveText('Session only');
  await $('input[type="password"]').setValue('synthetic-wordflow-portal-first');
  await $('button=Save token').click();
  await expect($('p=Token configured · This host session')).toBeDisplayed();
  await expect($('input[type="password"]')).toHaveValue('');
  await $('input[type="password"]').setValue('synthetic-wordflow-portal-replacement');
  await $('button=Replace token').click();
  await expect($('input[type="password"]')).toHaveValue('');
  const status = await browser.tauri.execute(({ core }) => core.invoke('get_backend_status') as Promise<{url:string}>);
  const response = await fetch(`${status.url}/api/portal/credential`);
  expect(response.status).toBe(200);
  const credential = await response.json();
  expect(credential).toEqual({ has_credential: true, credential_mode: 'session', credential_error: null });
  expect(JSON.stringify(await getTestPreferences())).not.toContain('synthetic-wordflow-portal');
  await $('button=Clear token').click();
  await expect($('[role="alertdialog"]').$('button=Cancel')).toBeFocused();
  await $('[role="alertdialog"]').$('button=Clear token').click();
  await expect($('[role="alertdialog"]')).not.toExist();
  await expect($('p=No token configured')).toBeDisplayed();
  await expect(settings.$('button=Portal')).toBeFocused();
  await settings.$('button=Storage').click();
  await expect($('h2=Storage locations')).toBeDisplayed();
  await expect($('[aria-label="Open Configuration folder"]')).toExist();
  await settings.$('button=Guidance').click();
  await expect($('[role="switch"]')).toHaveAttribute('data-state', 'checked');
  await settings.$('button=Close').click();
  await expect($('[aria-label="Open settings"]')).toBeFocused();
  await $('[data-testid="sidebar-section-tools"]').$('button=Export').click();
  const hint = $('[data-guidance-popup="export.setup"]');
  await expect(hint).toBeDisplayed();
  expect(await browser.execute(() => document.activeElement?.textContent?.trim())).toBe('Export');
  await expect($('[data-guidance-highlighted="true"]')).toBeDisplayed();
  await browser.keys('Escape');
  await expect(hint).not.toExist();
  await expect($('[data-guidance-highlighted]')).not.toExist();
  await $('[data-testid="sidebar-section-tools"]').$('button=Data Loader').click();
  await $('[data-guidance-popup="data-loader.setup"]').$('button=Got it').click();
  const importHint = $('[data-guidance-popup="data-loader.action"]');
  await expect(importHint).toHaveText(expect.stringContaining('imports them immediately'));
  await expect($('[data-guidance-highlighted]')).toHaveText(expect.stringContaining('Choose files'));
  await browser.saveScreenshot('native-data-loader-guidance.png');
  await importHint.$('button=Not now').click();
  await $('[data-testid="sidebar-section-tools"]').$('button=Annotation').click();
  await $('[role="tab"]=AI').click();
  await $('button=Manage connections').click();
  await expect($('h2=AI connections')).toBeDisplayed();
  await settings.$('button=Close').click();
  await expect($('button=Manage connections')).toBeFocused();
  await expect($('[role="tab"]=AI')).toHaveAttribute('data-state', 'active');
});
